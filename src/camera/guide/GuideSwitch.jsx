import './CameraGuide.css'

// Пояснение и выключатель помощника в форме отчёта. Это единственный способ узнать о помощнике и выключить его
// без ссылки: общего чата у клинеров нет.
export default function GuideSwitch({ isOn, onChange }) {
  return (
    <div className="cg-switch">
      <span>
        {isOn
          ? 'Помощник съёмки только подсказывает: снимать и отправлять можно всегда. Если он мешает или телефон тормозит, выключите его.'
          : 'Помощник съёмки выключен. Камера работает без подсказок.'}
      </span>
      <button type="button" onClick={() => onChange(!isOn)}>{isOn ? 'Выключить помощника' : 'Включить помощника'}</button>
    </div>
  )
}
